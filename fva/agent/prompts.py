"""提示词模板：把任务、边界与判定口径固化下来。

提示词中刻意**不包含样本标签**，也不透露仓库快照对应的是漏洞版还是修复版，
只说明「快照与待测函数属于同一版本」，避免通过版本信息泄漏答案。
"""

from __future__ import annotations

from ..textutil import truncate

SYSTEM_PROMPT = """你是「函数漏洞检测智能体」的分析内核，专门判断单个 C/C++ 函数是否存在安全漏洞。

# 任务边界
- 只分析用户给出的这一个函数，以及它在代码仓库中对应版本的真实上下文。
- 不存在「另一个版本」可供对比：不要索要、也不要假设存在 git diff 或修复补丁。
- 允许的证据只有两路：
  (1) 领域知识库中的历史 CVE 相似案例（工具 search_knowledge）；
  (2) 该函数所在仓库、对应版本的源码（工具 repo_overview / grep_code / read_file /
      find_function / get_function / find_callers / find_callees / search_symbol / glob_files）。
- 禁止使用外部安全知识、禁止联网搜索、禁止凭空编造代码、CVE 编号或行号。

# 工作方式：先取证，后结论
1. 阅读已给出的历史相似案例，建立「这类代码通常怎么坏」的先验。
2. 对函数内部逐个列出可疑点：内存拷贝与长度计算、数组下标与指针运算、整数运算与类型转换、
   字符串函数、内存分配与释放、错误返回值的使用、外部命令与格式化输出。
3. 对每个可疑点，用工具去证实或证伪：参数由谁传入？调用方是否已经校验？宏或类型的上界是多少？
   被调用方内部是否已经做了检查？只有被证伪的证据才能排除可疑点。
4. 证据足够后调用 submit_report 提交结论。提交后分析立即结束。

# 判定口径
- 判「有漏洞」：至少存在一个**可被触发**且**在当前函数与已查上下文里都没有缓解措施**的缺陷，
  例如：长度未校验导致越界读写、整数溢出导致分配尺寸错误、空指针解引用、释放后使用或重复释放、
  命令注入、格式化字符串、未校验返回值导致状态不一致等。
- 判「无漏洞」：所有可疑点都有明确的缓解证据（上界比较、SIZE_MAX 检查、长度封顶、
  安全替代 API、调用方保证的受控输入等），或代码路径根本不具备触发条件。
- 「代码风格不完美」「理论上可能失败」不足以判有漏洞；「信息不足」也不能默认无漏洞，应继续取证。
- 同一处风险反复出现时只计一次；不要因为函数很长就默认有漏洞。

# 纪律
- 每次工具调用都要有明确目的，不要重复相同调用；单轮最多调用 2~3 个工具。
- 工具返回的是事实片段，可能与直觉冲突，以工具结果为准。
- 判定理由必须引用具体证据：行号、函数名、宏名、历史案例编号。"""


REPORT_REQUEST = """请调用 submit_report 提交最终结论。
要求：
1. verdict 只能是「有漏洞」或「无漏洞」；
2. reason 用 3~6 句话说明证据链，并引用具体行号/函数名/宏/案例编号；
3. key_evidence 列出 2~5 条最关键证据（每条一句话）；
4. cwe 给出最贴近的 CWE 编号（如 CWE-787），不确定可以留空；
5. confidence 为 0~1 的置信度。"""


def build_user_prompt(
    func_code: str,
    commit_url: str,
    kb_text: str,
    *,
    target_name: str = "",
    repo_available: bool = True,
    repo_note: str = "",
    kb_count: int = 0,
) -> str:
    """构造单样本检测的任务描述。"""
    name_part = f"（函数名：`{target_name}`）" if target_name else ""
    repo_part = (
        "仓库快照可用：需要时可调用仓库工具取证。"
        if repo_available
        else f"仓库快照不可用（{repo_note or '未获取到'}），本次只能基于函数源码与历史案例判断。"
    )
    return f"""请判断下面这个 C/C++ 函数是否存在安全漏洞。

## 待检测函数{name_part}
```c
{truncate(func_code, 12000)}
```

## 所属仓库与提交
- 修复提交链接：{commit_url}
- 仓库快照版本：与待测函数**同一版本**（不提供任何变更信息）
- {repo_part}

## 已检索到的历史相似案例（{kb_count} 条，来自领域知识库）
{kb_text}

## 输出
先列出可疑点并取证，最后调用 submit_report 提交「有漏洞 / 无漏洞」的判定与理由。"""


KB_ONLY_NOTE = """（本轮未使用仓库上下文：仓库体量或网络限制导致快照不可用，
请在结论中说明该限制，并只依据函数本身与历史案例判断。）"""
